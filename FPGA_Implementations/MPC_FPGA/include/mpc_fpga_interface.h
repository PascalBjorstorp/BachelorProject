/**
 * @file mpc_fpga_interface.h
 * @brief CPU <-> FPGA Interface for MPC Riccati-ADMM Solver
 *
 * AXI-Lite + AXI-Stream register map for the MPC FPGA IP core.
 *
 * Data flow model (AXI-Stream DMA):
 *   1. CPU packs state + horizon into DMA buffer (336 bytes, 21 beats)
 *   2. AXI DMA streams data to FPGA via AXI-Stream (input_stream)
 *   3. FPGA computes MPC solution
 *   4. CPU reads output registers via AXI-Lite
 *
 * AXI-Stream Format (128-bit words):
 *   Beat 0: [e_y | e_psi | vx | vy]
 *   Beat 1: [omega | steering | horizon_length | reserved]
 *   Beat 2..20: [ref_vx[i] | ref_kappa[i] | ref_left[i] | ref_right[i]]
 *
 * Data format: all values are Q16.16 fixed-point (int32_t).
 *
 * Register offsets auto-generated by Vitis HLS 2025.1.
 * See: mpc_fpga_hls/ultra96v2/impl/misc/drivers/mpc_fpga_top_v1_0/src/xmpc_fpga_top_hw.h
 */

#ifndef MPC_FPGA_INTERFACE_H
#define MPC_FPGA_INTERFACE_H

#include <stdint.h>

/*===========================================================================
 * Base Addresses (set in Vivado Address Editor)
 *===========================================================================*/

#define MPC_FPGA_BASE_ADDR      0xA0010000  /* MPC IP AXI-Lite control */
#define AXI_DMA_BASE_ADDR       0xA0000000  /* AXI DMA controller */
#define DMA_BUFFER_PHYS_ADDR    0x70000000  /* Reserved memory for DMA */

/*===========================================================================
 * MPC IP AXI-Lite Registers (ctrl bundle)
 *===========================================================================
 * Offsets from HLS-generated xmpc_fpga_top_hw.h
 *===========================================================================*/

/* Control registers */
#define REG_AP_CTRL             0x00    /* bit0=start, bit1=done, bit2=idle, bit3=ready */
#define REG_GIE                 0x04    /* Global Interrupt Enable */
#define REG_IER                 0x08    /* IP Interrupt Enable */
#define REG_ISR                 0x0C    /* IP Interrupt Status (TOW) */

/* Output registers (Read-Only) */
#define REG_OUT_STEERING        0x10    /* Steering command [Q16.16] */
#define REG_OUT_STEERING_VLD    0x14    /* out_steering valid flag (COR) */
#define REG_OUT_ACCEL           0x20    /* Acceleration command [Q16.16] */
#define REG_OUT_ACCEL_VLD       0x24    /* out_accel valid flag (COR) */
#define REG_OUT_STATUS          0x30    /* Status code: 0=OK, 1=max_iter, 2=error, 3=no_traj */
#define REG_OUT_STATUS_VLD      0x34    /* out_status valid flag (COR) */
#define REG_OUT_ITERATIONS      0x40    /* ADMM iterations used */
#define REG_OUT_ITERATIONS_VLD  0x44    /* out_iterations valid flag (COR) */

/* AP_CTRL bit definitions */
#define AP_START                0x01
#define AP_DONE                 0x02
#define AP_IDLE                 0x04
#define AP_READY                0x08
#define AP_AUTO_RESTART         0x80

/*===========================================================================
 * AXI DMA Registers (MM2S channel for streaming to FPGA)
 *===========================================================================*/

#define DMA_MM2S_CTRL           0x00    /* MM2S Control register */
#define DMA_MM2S_STATUS         0x04    /* MM2S Status register */
#define DMA_MM2S_SRC_LO         0x18    /* Source Address (low 32 bits) */
#define DMA_MM2S_SRC_HI         0x1C    /* Source Address (high 32 bits) */
#define DMA_MM2S_LENGTH         0x28    /* Transfer Length (triggers DMA) */

/* DMA control bits */
#define DMA_CTRL_RUN            0x0001  /* Start DMA */
#define DMA_CTRL_RESET          0x0004  /* Reset DMA channel */

/* DMA status bits */
#define DMA_STATUS_HALTED       0x0001  /* DMA halted */
#define DMA_STATUS_IDLE         0x0002  /* DMA idle (transfer complete) */
#define DMA_STATUS_ERR_INT      0x4000  /* Internal error interrupt */
#define DMA_STATUS_ERR_SLV      0x0020  /* Slave error */
#define DMA_STATUS_ERR_DEC      0x0040  /* Decode error */

/*===========================================================================
 * MPC Configuration
 *===========================================================================*/

#define MPC_HORIZON             10                          /* Prediction horizon (steps) */
#define DMA_BUFFER_BEATS        MPC_HORIZON + 2             /* 2 header + reference beats */
#define DMA_BUFFER_BYTES        DMA_BUFFER_BEATS * 16       /* 21 beats × 16 bytes */

/*===========================================================================
 * Status Codes
 *===========================================================================*/

#define MPC_FPGA_STATUS_OK              0   /* Optimal solution found */
#define MPC_FPGA_STATUS_MAX_ITER        1   /* Hit iteration limit */
#define MPC_FPGA_STATUS_ERROR           2   /* Solver error */
#define MPC_FPGA_STATUS_NO_TRAJECTORY   3   /* No valid trajectory */

#endif /* MPC_FPGA_INTERFACE_H */
