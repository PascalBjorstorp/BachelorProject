/**
 * @file mpc_fpga_interface.h
 * @brief CPU <-> FPGA Interface for MPC Riccati-ADMM Solver
 *
 * AXI-Lite register map for the MPC FPGA IP core.
 * Follows the same mode-based pattern as the PP_FPGA implementation.
 *
 * Modes:
 *   0 = Compute: solve MPC from vehicle state, return steering + accel
 *   1 = Load waypoint: store one trajectory point in FPGA BRAM
 *   2 = Finalize: set total waypoint count, mark trajectory as loaded
 *
 * Data format: all values are Q16.16 fixed-point (int32_t).
 */

#ifndef MPC_FPGA_INTERFACE_H
#define MPC_FPGA_INTERFACE_H

#include <stdint.h>

/*===========================================================================
 * Memory Map — AXI-Lite Registers
 *===========================================================================
 * Base address set in Vivado Address Editor (e.g., 0xA0000000).
 * Offsets are auto-generated by Vitis HLS from the s_axilite interface.
 * The values below are approximate — check xmpc_fpga_top_hw.h after
 * synthesis for exact offsets.
 *===========================================================================*/

#define MPC_FPGA_BASE_ADDR      0xA0000000

/* --- AXI-Lite Control Registers --- */
#define REG_AP_CTRL             0x000   /* bit0=start, bit1=done, bit2=idle */
#define REG_GIE                 0x004
#define REG_IER                 0x008
#define REG_ISR                 0x00C

/* --- Mode Selection (R/W) --- */
#define REG_MODE                0x010   /* 0=compute, 1=load_wp, 2=finalize */

/* --- Waypoint Loading (mode=1) --- */
#define REG_WP_INDEX            0x018
#define REG_WP_X                0x020   /* X position Q16.16  */
#define REG_WP_Y                0x028   /* Y position Q16.16  */
#define REG_WP_PSI              0x030   /* Heading Q16.16     */
#define REG_WP_VX               0x038   /* Ref velocity Q16.16 */
#define REG_WP_KAPPA            0x040   /* Curvature Q16.16   */
#define REG_WP_AX               0x048   /* Ref accel Q16.16   */
#define REG_WP_LEFT_BOUND       0x050   /* Left wall Q16.16   */
#define REG_WP_RIGHT_BOUND      0x058   /* Right wall Q16.16  */
#define REG_WP_TOTAL            0x060   /* Total count (mode=2)*/

/* --- Vehicle State (mode=0, R/W) --- */
#define REG_ST_X                0x068   /* Global X Q16.16    */
#define REG_ST_Y                0x070   /* Global Y Q16.16    */
#define REG_ST_THETA            0x078   /* Heading Q16.16     */
#define REG_ST_VX               0x080   /* Longitudinal vel   */
#define REG_ST_VY               0x088   /* Lateral vel        */
#define REG_ST_OMEGA            0x090   /* Yaw rate           */
#define REG_ST_STEERING         0x098   /* Actual servo angle */
#define REG_ST_WP_IDX           0x0A0   /* Closest WP index   */

/* --- Output Registers (Read-Only) --- */
#define REG_OUT_STEERING        0x0A8   /* Steering cmd Q16.16 */
#define REG_OUT_ACCEL           0x0B0   /* Accel cmd Q16.16    */
#define REG_OUT_STATUS          0x0B8   /* 0=optimal, 1=max_iter, 2=error */
#define REG_OUT_ITERATIONS      0x0C0   /* ADMM iterations used */

/*===========================================================================
 * Status Codes
 *===========================================================================*/

#define MPC_FPGA_STATUS_OK              0
#define MPC_FPGA_STATUS_MAX_ITER        1
#define MPC_FPGA_STATUS_ERROR           2
#define MPC_FPGA_STATUS_NO_TRAJECTORY   3

/*===========================================================================
 * Trajectory Configuration
 *===========================================================================*/

#define MPC_FPGA_MAX_TRAJECTORY_SIZE    1024

#endif /* MPC_FPGA_INTERFACE_H */
